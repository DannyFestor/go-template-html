package hooks_test

import "testing"

const dropGeneratedCoverageScript = "drop-generated-coverage.sh"

func TestDropGeneratedCoverageKeepsOnlyHandWrittenFiles(t *testing.T) {
	t.Parallel()

	module := moduleWithCoverage(t)
	writeFile(t, module, "internal/view/page_templ.go", "// Code generated by templ - DO NOT EDIT.\n\npackage view\n")
	writeFile(t, module, coverageProfile, coverageProfileContent+
		"example.com/shop/internal/view/page_templ.go:3.1,9.2 10 0\n")

	run := runScript(t, module, "", dropGeneratedCoverageScript, coverageProfile)

	requirePassed(t, run)

	if run.output != coverageProfileContent {
		t.Errorf("output = %q, want %q", run.output, coverageProfileContent)
	}
}
