func TestAddedCommentsAreDenied(t *testing.T) {
	t.Parallel()

	requireDecisions(t, []editTest{
		{insertion("internal/a.go", "n++ // increments the counter\n"), decision.Deny, "// increments the counter"},
		{insertion("internal/a.go", "/* block */\n"), decision.Deny, "/* block */"},
		{insertion("internal/a.go", "s := `C:\\`\n// after a raw string\n"), decision.Deny, "// after a raw string"},
		{insertion("internal/a.ts", "// explains what\n"), decision.Deny, "// explains what"},
		{insertion("internal/a.ts", "// oxlint-disable\n"), decision.Deny, "oxlint-disable"},
		{insertion("internal/a.ts", "// eslint-disable-next-line no-console\n"), decision.Deny, "eslint"},
		{insertion("internal/view/a.templ", "<!-- note -->\n"), decision.Deny, "<!-- note -->"},
		{insertion("internal/view/a.templ", "// note\n"), decision.Deny, "// note"},
		{insertion("queries/a.sql", "SELECT 1; -- explains\n"), decision.Deny, "-- explains"},
		{insertion("scripts/a.sh", "# explains\n"), decision.Deny, "# explains"},
	})
}

