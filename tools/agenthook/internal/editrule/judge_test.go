func TestDirectivesAndNonCommentsPass(t *testing.T) {
	t.Parallel()

	passes := []editrule.Edit{
		insertion("internal/a.go", "func f() { //nolint:funlen // table test\n"),
		insertion("internal/a.go", "//go:embed all:dist\n"),
		insertion("internal/a.go", "//lint:ignore\n"),
		insertion("internal/a.go", `url := "https://example.com" + '"'`+"\n"),
		insertion("internal/a.go", "key := \"x\" // gitleaks:allow\n"),
		insertion("internal/a.ts", "// @ts-expect-error the types lag behind\n"),
		insertion("internal/a.ts", "/// <reference types=\"vite/client\" />\n"),
		insertion("internal/a.ts", "// oxlint-disable-next-line no-console\n"),
		insertion("internal/a.ts", "/* oxlint-disable unicorn/no-null, no-console */\n"),
		insertion("internal/a.ts", "const s = `a // b` + \"// c\" + '// d';\n"),
		insertion("internal/view/a.templ", "<p>Don't miss https://example.com</p>\n"),
		insertion("queries/a.sql", "-- name: GetUser :one\nSELECT '--x';\n"),
		insertion("migrations/1_a.sql", "-- +goose Up\n"),
		insertion("scripts/a.sh", "#!/bin/sh\n# shellcheck disable=SC2086\necho \"${#x} # y\" a#b\n"),
		insertion("lefthook.yml.md", "# heading\n"),
		{Path: "internal/a.go", Original: "", Removed: "// keep\nn := 1\n", Inserted: "// keep\nn := 2\n"},
	}

	for _, edit := range passes {
		requireDecisions(t, []editTest{{edit, decision.Pass, ""}})
	}
}

func TestResubmittedCommentsAsk(t *testing.T) {
	t.Parallel()

	judge := editrule.NewJudge(fakeMemory{})
	edit := insertion("internal/a.go", "n++ // increments the counter\n")

	first := judgeEdit(t, judge, edit)
	second := judgeEdit(t, judge, edit)

	if first.Verdict != decision.Deny || second.Verdict != decision.Ask {
		t.Errorf("verdicts = %v then %v, want deny then ask", first.Verdict, second.Verdict)
	}
}

func TestDeniedEditsDoNotRememberComments(t *testing.T) {
	t.Parallel()

	memory := fakeMemory{}
	judge := editrule.NewJudge(memory)

	judgeEdit(t, judge, insertion("go.sum", "// note\n"))

	if len(memory) != 0 {
		t.Errorf("remembered %v after a generated-output deny, want nothing", memory)
	}
}

func judgeEdit(t *testing.T, judge editrule.Judge, edit editrule.Edit) decision.Decision {
	t.Helper()

	got, err := judge.Edit(edit)
	if err != nil {
		t.Fatalf("Edit(%+v): %v", edit, err)
	}

	return got
}

func requireDecisions(t *testing.T, tests []editTest) {
	t.Helper()

	for _, test := range tests {
		got := judgeEdit(t, editrule.NewJudge(fakeMemory{}), test.edit)
		if got.Verdict != test.want || !strings.Contains(got.Reason, test.wantReason) {
			t.Errorf(
				"Edit(%+v) = %v %q, want %v containing %q",
				test.edit,
				got.Verdict,
				got.Reason,
				test.want,
				test.wantReason,
			)
		}
	}
}
