package editrule_test

import (
	"strings"
	"testing"

	"github.com/DannyFestor/go-template-html/tools/agenthook/internal/decision"
	"github.com/DannyFestor/go-template-html/tools/agenthook/internal/editrule"
)

type fakeMemory map[string]bool

func (f fakeMemory) Seen(comment string) bool {
	return f[comment]
}

func (f fakeMemory) Remember(comments []string) error {
	for _, comment := range comments {
		f[comment] = true
	}

	return nil
}

func insertion(path, inserted string) editrule.Edit {
	return editrule.Edit{Path: path, Original: "", Removed: "", Inserted: inserted}
}

type editTest struct {
	edit       editrule.Edit
	want       decision.Verdict
	wantReason string
}

func TestGeneratedOutputIsDenied(t *testing.T) {
	t.Parallel()

	templOutput := "// Code generated by templ - DO NOT EDIT.\n\npackage view\n"

	requireDecisions(t, []editTest{
		{
			editrule.Edit{Path: "internal/view/home_templ.go", Original: templOutput, Removed: "a", Inserted: "b"},
			decision.Deny, "make generate",
		},
		{
			insertion("internal/store/queries.sql.go", "// Code generated by sqlc. DO NOT EDIT.\n"),
			decision.Deny,
			"make generate",
		},
		{insertion("internal/asset/dist/app.js", "x"), decision.Deny, "make vite-build"},
		{insertion("migrations/migrations.sum", "x"), decision.Deny, "make generate"},
		{insertion("go.sum", "x"), decision.Deny, "go mod tidy"},
		{insertion("tools/agenthook/go.sum", "x"), decision.Deny, "go mod tidy"},
		{insertion("pnpm-lock.yaml", "x"), decision.Deny, "bin/vp add"},
		{insertion("internal/view/home.go", "package view\n"), decision.Pass, ""},
	})
}

