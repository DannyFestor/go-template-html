func TestShellFileWritesIntoTheRepoAreDenied(t *testing.T) {
	t.Parallel()

	repo := newRepo(t)

	denied := []string{
		`echo x > internal/foo.go`,
		`sed -i 's/x/y/' Makefile`,
		"python3 - <<EOF\nopen('internal/foo.go', 'w').write('x')\nEOF",
	}
	for _, command := range denied {
		requirePermission(
			t,
			runHook(t, "pre-tool-use", "pre_tool_use_bash", bashCall(repo, command)),
			"deny",
			"edit tools",
		)
	}

	passed := []string{`echo x > "$TMPDIR/out"`, `git commit -m"Add login"`}
	for _, command := range passed {
		requirePassed(t, runHook(t, "pre-tool-use", "pre_tool_use_bash", bashCall(repo, command)))
	}
}

func TestPushingABranchFromALinkedWorktreePassesWhileMainIsCheckedOut(t *testing.T) {
	t.Parallel()

	repo := newRepo(t)
	worktree := addWorktree(t, repo, "feature")

	passed := []hookCall{
		bashCall(worktree, `git push origin feature`),
		bashCall(worktree, `git push`),
		bashCall(repo, `cd `+worktree+` && git push`),
		bashCall(repo, `cd "$(mktemp -d)" && git push`),
	}
	for _, call := range passed {
		requirePassed(t, runHook(t, "pre-tool-use", "pre_tool_use_bash", call))
	}

	denied := []hookCall{
		bashCall(repo, `git push`),
		bashCall(worktree, `git push origin HEAD:main`),
		bashCall(filepath.Dir(worktree), `git -C `+repo+` push origin`),
	}
	for _, call := range denied {
		requirePermission(t, runHook(t, "pre-tool-use", "pre_tool_use_bash", call), "deny", "pull request")
	}
}

