package main_test

import (
	"path/filepath"
	"testing"
)

const session = "4b8c1e2a-session"

func editCall(cwd, path, oldString, newString string) hookCall {
	return hookCall{
		SessionID: session,
		Cwd:       cwd,
		FilePath:  path,
		OldString: oldString,
		NewString: newString,
		Content:   "",
		Command:   "",
	}
}

func writeCall(cwd, path, content string) hookCall {
	return hookCall{
		SessionID: session,
		Cwd:       cwd,
		FilePath:  path,
		OldString: "",
		NewString: "",
		Content:   content,
		Command:   "",
	}
}

func bashCall(cwd, command string) hookCall {
	return hookCall{
		SessionID: session,
		Cwd:       cwd,
		FilePath:  "",
		OldString: "",
		NewString: "",
		Content:   "",
		Command:   command,
	}
}

func TestEditingAGeneratedFileIsDeniedAndNamesTheGenerator(t *testing.T) {
	t.Parallel()

	repo := newRepo(t)
	path := commitFile(
		t,
		repo,
		"internal/view/home_templ.go",
		"// Code generated by templ - DO NOT EDIT.\n\npackage view\n",
	)

	result := runHook(t, "pre-tool-use", "pre_tool_use_edit", editCall(repo, path, "package view", "package views"))

	requirePermission(t, result, "deny", "make generate")
}

func TestAnAddedCommentIsDeniedThenAsksWhenResubmitted(t *testing.T) {
	t.Parallel()

	repo := newRepo(t)
	path := commitFile(t, repo, "internal/counter/counter.go", "package counter\n\nvar n = 1\n")
	call := editCall(repo, path, "var n = 1", "var n = 1 // increments the counter")

	requirePermission(t, runHook(t, "pre-tool-use", "pre_tool_use_edit", call), "deny", "// increments the counter")
	requirePermission(t, runHook(t, "pre-tool-use", "pre_tool_use_edit", call), "ask", "// increments the counter")

	call.SessionID = "another-session"
	requirePermission(t, runHook(t, "pre-tool-use", "pre_tool_use_edit", call), "deny", "// increments the counter")
}

